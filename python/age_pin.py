"""Run `age -d -i IDENTITY FILE` on a private pty and answer the YubiKey PIN
prompt with the first line of stdin.

Usage: age_pin.py IDENTITY FILE [TIMEOUT]

Prints the plaintext on stdout. On failure prints age's message instead
(PIN scrubbed) and exits non-zero. A second PIN prompt (wrong PIN) or no
result within TIMEOUT seconds (YubiKey not touched) kills age, so the caller
never hangs and no extra PIN retries are used up.

This code was generated by Claude (Anthropic's AI assistant).
"""
import os, pty, select, signal, sys, time

identity, path = sys.argv[1], sys.argv[2]
timeout = float(sys.argv[3]) if len(sys.argv) > 3 else 60
pin = sys.stdin.buffer.readline().rstrip(b"\r\n")

r, w = os.pipe()
pid, fd = pty.fork()
if pid == 0:
    os.dup2(w, 1); os.close(r); os.close(w)
    os.execvp("age", ["age", "-d", "-i", identity, path])
os.close(w)

out, tty, sent, err = b"", b"", False, None
fds, deadline = [fd, r], time.monotonic() + timeout
while r in fds and not err:
    left = deadline - time.monotonic()
    if left <= 0:
        err = "timed out waiting for the YubiKey (not touched?)"
        break
    for f in select.select(fds, [], [], left)[0]:
        try:
            d = os.read(f, 65536)
        except OSError:
            d = b""
        if not d:
            fds.remove(f)
        elif f == r:
            out += d
        else:
            tty += d
            n = tty.count(b"Enter PIN")
            if n > 1:
                err = "wrong PIN"
                break
            if n == 1 and not sent:
                time.sleep(0.2)   # let age switch off echo first
                os.write(fd, pin + b"\n")
                sent = True

if err:
    os.kill(pid, signal.SIGKILL)
code = os.waitstatus_to_exitcode(os.waitpid(pid, 0)[1])
if err or code:
    msg = err or (tty.replace(pin, b"") if sent and pin else tty).decode(errors="replace")
    sys.stdout.write(" ".join(msg.split()))
    sys.exit(code or 1)
sys.stdout.buffer.write(out)
